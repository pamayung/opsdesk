def backdate_resolved(code, days=8):
    """Menggeser seluruh waktu tiket Resolved ke belakang (penjaga tiket dimatikan sementara, hanya di database uji)."""
    d = f"interval '{days} days'"
    sql = f"begin; alter table opsdesk.tickets disable trigger tickets_guard_trg; update opsdesk.tickets set created_at = created_at - {d}, responded_at = responded_at - {d}, respond_due_at = respond_due_at - {d}, resolve_due_at = resolve_due_at - {d}, resolved_at = resolved_at - {d} where code = '{code}'; alter table opsdesk.tickets enable trigger tickets_guard_trg; commit;"
    subprocess.run(['psql', ADMIN_DB, '-v', 'ON_ERROR_STOP=1', '-q', '-c', sql], check=True)

